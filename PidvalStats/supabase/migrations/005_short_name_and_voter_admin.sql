-- Ручне коротке ім'я (прізвище) для показу в схемі складу. Якщо порожнє —
-- код сам бере останнє слово з full_name (працює для більшості імен;
-- для складених прізвищ типу "тер Штеген", "де Йонг" — вписати вручну).
alter table players add column if not exists short_name text;

-- Дозволяємо admin-у видаляти фанатів (voters) — раніше такої політики
-- не було, тільки insert/select.
drop policy if exists "admins delete voters" on voters;
create policy "admins delete voters" on voters
  for delete using (is_admin((auth.jwt() ->> 'voter_id')::uuid));
